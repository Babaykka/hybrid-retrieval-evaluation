"""Generate bilingual LaTeX tables from the verified evaluation summaries."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--package", type=Path, default=ROOT / "package")
OUT = parser.parse_args().package
M = json.loads((ROOT / "results/manual_summary.json").read_text())
F = json.loads((ROOT / "results/fullset_summary.json").read_text())
ROWS = F["populations"]["all_queries"]["depths"]


def number(value):
    return f"{value:,}".replace(",", r"\,")


def write(name, body):
    path = OUT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body + "\n", encoding="utf-8")


def table(name, caption, label, columns, headers, rows):
    write(name, "\n".join([
        r"\begin{table}[t]", r"\caption{" + caption + "}",
        r"\label{" + label + "}", r"\centering\small",
        r"\begin{tabularx}{\textwidth}{@{}" + columns + "@{}}",
        r"\toprule", " & ".join(headers) + r" \\", r"\midrule",
        *[" & ".join(row) + r" \\" for row in rows],
        r"\bottomrule", r"\end{tabularx}", r"\end{table}",
    ]))


test = M["judge_rescored_split_metrics"]["test"]
macros = {
    "ManualQueryCount": number(M["queries"]), "ManualPairCount": number(M["pairs"]),
    "FullQueryCount": number(F["populations"]["all_queries"]["query_count"]),
    "JudgeTestAuc": f'{test["auc"]:.3f}', "JudgeTestFOne": f'{test["f1"]:.3f}',
    "JudgeTestPrecision": f'{test["precision"]:.3f}', "JudgeTestRecall": f'{test["recall"]:.3f}',
    "JudgeHeldoutOriginalNdcg": f'{M["judge_rerank_heldout"]["official"]:.3f}',
    "JudgeHeldoutHumanNdcg": f'{M["judge_rerank_heldout"]["human"]:.3f}',
    "FullPositiveLargeConditional": f'{ROWS[-1]["positives_mean_positive_queries"]:.2f}',
}
for key, prefix in [("official", "Original"), ("human", "Human"), ("judge", "Judge")]:
    macros[prefix + "PositiveCount"] = number(M["density"][key]["pairs"])
    macros[prefix + "MeanRel"] = f'{M["density"][key]["mean"]:.2f}'
for key, prefix in [("bm25", "Bm"), ("e5", "E")]:
    macros[prefix + "Original"] = f'{M["metrics"][key]["official"]:.3f}'
    macros[prefix + "Human"] = f'{M["metrics"][key]["human"]:.3f}'
for row, prefix in [(ROWS[0], "Small"), (ROWS[-1], "Large")]:
    macros["FullPool" + prefix] = f'{row["candidates_mean_all_queries"]:.2f}'
    macros["FullPositive" + prefix] = f'{row["positives_mean_all_queries"]:.2f}'
write("results_macros.tex", "% Generated by build_tables.py from evaluation summaries.\n" +
      "\n".join("\\newcommand{\\" + k + "}{" + v + "}" for k, v in macros.items()))

for lang in ["en", "ru"]:
    en = lang == "en"
    table(f"tables/manual_data_{lang}.tex",
          ("Annotation coverage within the same manual candidate pool. Automatic predictions are not additional human assessments."
           if en else "Охват разметки в одном и том же ручном пуле. Автоматические метки не являются дополнительными человеческими оценками."),
          "tab:annotation-data", "Lrrr",
          (["Quantity", "Original", "Human", "Judge"] if en else ["Показатель", "Исходная", "Ручная", "Судья"]),
          [(["Queries"] if en else ["Запросов"]) + [number(M["queries"])] * 3,
           (["Candidate pairs"] if en else ["Пар в пуле"]) + [number(M["pairs"])] * 3,
           (["Positive pairs"] if en else ["Положительных пар"]) + [number(M["density"][x]["pairs"]) for x in ["official", "human", "judge"]],
           (["Positives per query, mean"] if en else ["Положительных на запрос, среднее"]) + [f'{M["density"][x]["mean"]:.2f}' for x in ["official", "human", "judge"]],
           (["Positives per query, median"] if en else ["Положительных на запрос, медиана"]) + [str(int(M["density"][x]["median"])) for x in ["official", "human", "judge"]]])
    rows = []
    for model, name in [("bm25", "BM25"), ("e5", "E5"), ("bge", "BGE"), ("rrf3", "RRF(3)")]:
        value = M["metrics"][model]
        effect = value["human_minus_official"]
        rows.append([name, f'{value["official"]:.3f}', f'{value["human"]:.3f}',
                     f'+{effect["mean"]:.3f}', f'[{effect["ci95"][0]:.3f}, {effect["ci95"][1]:.3f}]'])
    table(f"tables/manual_results_{lang}.tex",
          (r"Pooled NDCG@10 before and after manual annotation on all 1,179 queries. These are not full-corpus leaderboard scores. $\Delta$ is human minus original; intervals are paired 95\% bootstrap intervals."
           if en else r"NDCG@10 в пуле до и после ручной доразметки на всех 1\,179 запросах; это не оценки по полному корпусу. $\Delta$: ручная минус исходная разметка; интервалы: парный 95\%-й бутстреп."),
          "tab:manual-results", "Lrrrr",
          (["System", "Original", "Human", r"$\Delta$", r"95\% CI"] if en else ["Система", "Исходная", "Ручная", r"$\Delta$", r"95\% ДИ"]), rows)
    rows = [["Base / " + ("validation" if en else "валидация"), "177", r"5\,122", "0.865", "--", "--", "--"]]
    for split, title in [("validation", "Fine-tuned / validation" if en else "Дообуч. / валидация"), ("test", "Fine-tuned / test" if en else "Дообуч. / тест")]:
        row = M["judge_rescored_split_metrics"][split]
        rows.append([title, str(row["queries"]), number(row["n"]), *[f'{row[x]:.3f}' for x in ["auc", "f1", "precision", "recall"]]])
    table(f"tables/judge_results_{lang}.tex",
          ("Judge agreement. The base validation AUC is the recorded training baseline; fine-tuned metrics are recomputed from saved scores. P: precision; R: recall."
           if en else "Качество судьи. AUC базовой модели взят из записи обучения; метрики дообученной модели пересчитаны по сохранённым оценкам. P: точность; R: полнота."),
          "tab:judge-results", "Lrrrrrr",
          (["Model / subset", "Queries", "Pairs", "AUC", "F1", "P", "R"] if en else ["Модель / выборка", "Запр.", "Пар", "AUC", "F1", "P", "R"]), rows)
    rows = []
    for row in ROWS:
        rows.append([str(row["k"]), f'{row["candidates_mean_all_queries"]:.2f}', f'{row["positives_mean_all_queries"]:.2f}',
                     *[f'{row["models"][x]["ndcg10_mean_all_queries"]:.3f}' for x in ["bm25", "e5", "bge", "rrf_variable"]]])
    table(f"tables/fullset_results_{lang}.tex",
          ("Full-set pseudo-label evaluation on all 101,093 queries, including zero-positive pools. Pool and positive counts are means per query; system columns are NDCG@10. RRF input depth equals $K$. Paired intervals and tests use 2,000 query resamples/randomizations, seed 20260914."
           if en else r"Оценка по псевдометкам на всех 101\,093 запросах, включая пулы без положительных меток. Величина пула и число положительных меток усреднены по запросам; для систем приведён NDCG@10. Глубина входа RRF равна $K$. Парные интервалы и тесты используют 2\,000 повторов, seed 20260914."),
          "tab:fullset", "Lrrrrrr",
          (["$K$", "Pool", "Positive", "BM25", "E5", "BGE", "RRF(3)"] if en else ["$K$", "Пул", "Полож.", "BM25", "E5", "BGE", "RRF(3)"]), rows)

stats = [r for r in F["paired_inference"]["all_queries"] if r["contrast"] == "rrf_variable_minus_e5"]
clean = F["populations"]["excluding_manual_queries"]
clean_effect = next(r for r in F["paired_inference"]["excluding_manual_queries"] if r["k"] == 200 and r["contrast"] == "rrf_variable_minus_e5")
ci = stats[-1]["bootstrap_ci95"]
fixed10 = ROWS[0]["models"]["rrf_fixed200"]
write("fullset_interpretation_en.tex", rf"""RRF(3) is below E5 at $K=10$ (0.852 versus 0.871), but above it at all four larger tested depths. At $K=200$, the paired difference is $+{stats[-1]['mean_delta']:.4f}$, with 95\% CI $[{ci[0]:.4f}, {ci[1]:.4f}]$. All five depth-specific contrasts have unadjusted paired $p<0.001$; they also pass a Bonferroni correction for these five comparisons at level 0.05. This is agreement with the fixed judge, not independently established human relevance superiority.

The individual retrievers' top-ten DCG values stay constant as $K$ grows: only their shared ideal denominator changes. In contrast, deeper RRF inputs can change the fused ranking itself. Keeping fusion input fixed at 200 gives NDCG 0.805 at assessment depth ten and 0.850 at depth 200. At depth ten, {number(fixed10['top10_outside_pool_total'])} of its returned query--passage pairs lie outside the assessed pool and receive zero gain. This diagnostic separates missing judgments from the effect of truncating fusion inputs.

All 1,179 manual queries occur in the full set, so the full-set analysis is not a wholly independent held-out evaluation. Excluding them leaves {number(clean['query_count'])} queries. At depth 200 the RRF-minus-E5 difference is still $+{clean_effect['mean_delta']:.4f}$ (95\% CI $[{clean_effect['bootstrap_ci95'][0]:.4f}, {clean_effect['bootstrap_ci95'][1]:.4f}]$), and the direction of all five depth comparisons is unchanged. The score audit covers all {number(ROWS[-1]['candidate_pairs'])} candidate pairs with no missing scores; {number(ROWS[-1]['zero_idcg_queries'])} queries have no positive prediction at depth 200.""")
write("fullset_interpretation_ru.tex", rf"""RRF(3) уступает E5 при $K=10$ (0.852 против 0.871), но превосходит его при всех четырёх больших исследованных глубинах. При $K=200$ парная разность равна $+{stats[-1]['mean_delta']:.4f}$, 95\%-й ДИ $[{ci[0]:.4f}, {ci[1]:.4f}]$. Для всех пяти сравнений нескорректированное парное $p<0.001$; они также проходят поправку Бонферрони для пяти проверок при уровне 0.05. Это согласие с фиксированным судьёй, а не независимо подтверждённое превосходство по человеческим оценкам.

DCG первых десяти результатов отдельных поисковых моделей не меняется при росте $K$: изменяется лишь общий идеальный знаменатель. Более глубокие входные списки RRF, напротив, могут менять само итоговое ранжирование. При фиксированной глубине входа RRF, равной 200, NDCG составляет 0.805 при глубине разметки десять и 0.850 при глубине 200. В первом случае {number(fixed10['top10_outside_pool_total'])} возвращённых пар находятся вне размеченного пула и получают нулевой вклад. Эта проверка отделяет неполноту разметки от усечения входов слияния.

Все 1\,179 запросов ручной части входят в большой набор, поэтому он не является полностью независимой тестовой выборкой. Их исключение оставляет {number(clean['query_count'])} запросов. При глубине 200 разность RRF минус E5 сохраняется: $+{clean_effect['mean_delta']:.4f}$ (95\%-й ДИ $[{clean_effect['bootstrap_ci95'][0]:.4f}, {clean_effect['bootstrap_ci95'][1]:.4f}]$); направления всех пяти сравнений также не меняются. Проверены оценки для всех {number(ROWS[-1]['candidate_pairs'])} пар без пропусков; при глубине 200 у {number(ROWS[-1]['zero_idcg_queries'])} запросов нет положительного предсказания.""")
print("Generated bilingual tables, numerical macros and full-set interpretation.")
