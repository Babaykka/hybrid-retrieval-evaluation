export function ru(value) {
  if (typeof value !== 'string') return value;
  if (Object.hasOwn(strings, value)) return strings[value];
  if (/^[+−-]?\d+\.\d+$/.test(value)) return value.replace('.', ',');
  return value;
}

export function localizeChart(value) {
  if (Array.isArray(value)) return value.map(localizeChart);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k,v]) => [k, /FormatCode$/.test(k) ? v : localizeChart(v)]));
  return ru(value);
}
